"""Generate pmdarima auto_arima order choices for the auto-ARIMA integration tests.

Writes `tests/it/auto_data.rs`. pmdarima pins its own numpy and statsmodels, so run
this from a separate virtual environment:

    python3 -m venv /tmp/pmdarima && /tmp/pmdarima/bin/pip install pmdarima
    /tmp/pmdarima/bin/python -I scripts/generate_auto_reference.py

`d` and `D` are fixed in every case, so the tests compare the stepwise search itself
rather than the differencing tests (pmdarima's KPSS lag rule and its OCSB seasonal
test differ from this crate's choices).
"""

import pathlib
import warnings

import numpy as np
import pmdarima

OUTPUT = pathlib.Path(__file__).resolve().parent.parent / "tests" / "it" / "auto_data.rs"


def simulate(ar, ma, n, seed, d=0, seasonal_ar=(), seasonal_ma=(), period=0, seasonal_d=0, mean=0.0):
    """A seasonal ARIMA series of `n` values after a 300-value burn-in."""
    rng = np.random.default_rng(seed)
    ar_poly = np.r_[1.0, -np.array(ar, float)]
    ma_poly = np.r_[1.0, np.array(ma, float)]
    if period:
        sar = np.zeros(len(seasonal_ar) * period + 1)
        sar[0] = 1.0
        for j, c in enumerate(seasonal_ar):
            sar[(j + 1) * period] = -c
        sma = np.zeros(len(seasonal_ma) * period + 1)
        sma[0] = 1.0
        for j, c in enumerate(seasonal_ma):
            sma[(j + 1) * period] = c
        ar_poly = np.convolve(ar_poly, sar)
        ma_poly = np.convolve(ma_poly, sma)
    burn = 300
    e = rng.standard_normal(n + burn)
    w = np.zeros_like(e)
    for t in range(len(w)):
        w[t] = e[t] + sum(ma_poly[j] * e[t - j] for j in range(1, len(ma_poly)) if t - j >= 0)
        w[t] -= sum(ar_poly[j] * w[t - j] for j in range(1, len(ar_poly)) if t - j >= 0)
    y = w[burn:] + mean
    for _ in range(seasonal_d):
        y = np.concatenate([np.zeros(period), y])
        for t in range(period, len(y)):
            y[t] += y[t - period]
        y = y[period:]
    for _ in range(d):
        y = np.cumsum(y)
    return y


CASES = [
    ("AR2", "AR(2), phi = (0.6, -0.3).", dict(ar=[0.6, -0.3], ma=[], n=150, seed=1), 0, 0, 0),
    ("MA1", "MA(1), theta = 0.6.", dict(ar=[], ma=[0.6], n=150, seed=2), 0, 0, 0),
    ("ARMA11", "ARMA(1, 1), phi = 0.7, theta = 0.4, mean 5.", dict(ar=[0.7], ma=[0.4], n=150, seed=3, mean=5.0), 0, 0, 0),
    ("WHITE", "White noise.", dict(ar=[], ma=[], n=150, seed=4), 0, 0, 0),
    ("I1", "ARIMA(1, 1, 0), phi = 0.5.", dict(ar=[0.5], ma=[], n=150, seed=5, d=1), 1, 0, 0),
    ("DRIFT", "A random walk with drift 0.3.", dict(ar=[], ma=[], n=150, seed=6, d=1, mean=0.3), 1, 0, 0),
    ("SAR12", "ARIMA(1, 0, 0)(1, 0, 0, 12), phi = 0.5, Phi = 0.6.", dict(ar=[0.5], ma=[], n=144, seed=7, seasonal_ar=[0.6], period=12), 0, 0, 12),
    ("AIRLINE12", "The airline model ARIMA(0, 1, 1)(0, 1, 1, 12), theta = -0.4, Theta = -0.6.", dict(ar=[], ma=[-0.4], n=144, seed=8, d=1, seasonal_ma=[-0.6], period=12, seasonal_d=1), 1, 1, 12),
]


def rust_array(values):
    """A Rust array literal that round-trips every float exactly."""
    return "&[\n" + "".join(f"        {float(v)!r},\n" for v in values) + "    ]"


def case(name, doc, simulation, d, seasonal_d, period):
    """Render one `AutoCase` constant."""
    y = simulate(**simulation)
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        model = pmdarima.auto_arima(
            y, d=d, D=seasonal_d, seasonal=period > 1, m=max(period, 1),
            start_p=2, start_q=2, start_P=1, start_Q=1,
            max_p=5, max_q=5, max_P=2, max_Q=2,
            information_criterion="aicc", stepwise=True,
            with_intercept="auto", suppress_warnings=True, error_action="ignore",
        )
    chosen_d = pmdarima.arima.ndiffs(y, alpha=0.05, test="kpss", max_d=2)
    p, _, q = model.order
    sp, _, sq, _ = model.seasonal_order
    return "\n".join([
        f"/// {doc}",
        f"pub const {name}: AutoCase = AutoCase {{",
        f"    values: {rust_array(y)},",
        f"    d: {d},",
        f"    seasonal_d: {seasonal_d},",
        f"    period: {period},",
        f"    orders: ({p}, {q}, {sp}, {sq}),",
        f"    constant: {str(bool(model.with_intercept)).lower()},",
        f"    ndiffs: {chosen_d},",
        "};",
    ])


def main():
    """Write the auto-ARIMA reference module."""
    header = f'''//! pmdarima `auto_arima` order choices.
//!
//! Generated by `scripts/generate_auto_reference.py` with pmdarima {pmdarima.__version__}.
//! Do not edit by hand; rerun the script instead.

/// One simulated series with the model pmdarima's stepwise AICc search picks for it.
pub struct AutoCase {{
    /// The series.
    pub values: &'static [f64],
    /// The fixed differencing order.
    pub d: usize,
    /// The fixed seasonal differencing order.
    pub seasonal_d: usize,
    /// The season length, or 0 for a non-seasonal search.
    pub period: usize,
    /// The selected `(p, q, P, Q)`.
    pub orders: (usize, usize, usize, usize),
    /// Whether the selected model has a mean or drift.
    pub constant: bool,
    /// `pmdarima.arima.ndiffs(values, alpha=0.05, test="kpss", max_d=2)`.
    pub ndiffs: usize,
}}

/// All auto-ARIMA reference cases.
pub const ALL: &[&AutoCase] = &[{", ".join(f"&{c[0]}" for c in CASES)}];

/// The names of [`ALL`], in the same order.
pub const NAMES: &[&str] = &[{", ".join(f'"{c[0]}"' for c in CASES)}];
'''
    OUTPUT.write_text(header + "\n" + "\n\n".join(case(*c) for c in CASES) + "\n")


if __name__ == "__main__":
    main()

# Diagnostics: acf, pacf and Box.test.
set.seed(201)
diagnostic <- as.numeric(arima.sim(list(ar = c(0.5, -0.2)), n = 120))
acf_values <- acf(diagnostic, lag.max = 10, plot = FALSE)$acf[-1]
pacf_values <- pacf(diagnostic, lag.max = 10, plot = FALSE)$acf
box <- Box.test(diagnostic, lag = 10, type = "Ljung-Box", fitdf = 2)
emit(
  "/// A simulated AR(2) series for `acf`, `pacf` and `Box.test`.",
  sprintf("pub const DIAGNOSTIC: &[f64] = %s;", rust_array(diagnostic)),
  "/// `acf(DIAGNOSTIC, lag.max = 10)$acf`, lags 1 to 10.",
  sprintf("pub const ACF: &[f64] = %s;", rust_array(acf_values)),
  "/// `pacf(DIAGNOSTIC, lag.max = 10)$acf`, lags 1 to 10.",
  sprintf("pub const PACF: &[f64] = %s;", rust_array(pacf_values)),
  "/// `Box.test(DIAGNOSTIC, lag = 10, type = \"Ljung-Box\", fitdf = 2)`: statistic and p-value.",
  sprintf("pub const LJUNG_BOX: [f64; 2] = [%s, %s];", rust_float(box$statistic), rust_float(box$p.value)),
  ""
)

# Fourier regressors, in-sample from t = 1 and for the horizon after the series.
fourier_series <- msts(seq_len(40), seasonal.periods = c(7, 30.5))
in_sample <- fourier(fourier_series, K = c(2, 3))
horizon <- fourier(fourier_series, K = c(2, 3), h = 5)
monthly <- fourier(ts(seq_len(24), frequency = 12), K = 6)
emit(
  "/// `fourier(msts(1:40, seasonal.periods = c(7, 30.5)), K = c(2, 3))`, row-major, rows",
  "/// for t = 1 to 40.",
  sprintf("pub const FOURIER_IN_SAMPLE: &[f64] = %s;", rust_array(t(in_sample))),
  "/// The same with `h = 5`: rows for t = 41 to 45.",
  sprintf("pub const FOURIER_HORIZON: &[f64] = %s;", rust_array(t(horizon))),
  "/// `fourier(ts(1:24, frequency = 12), K = 6)`, row-major: the Nyquist sine is dropped.",
  sprintf("pub const FOURIER_MONTHLY: &[f64] = %s;", rust_array(t(monthly))),
  ""
)

# Differencing tests and the automatic search.
auto_cases <- list(
  list(name = "AUTO_AR1", doc = "An AR(1) with a mean.", period = 1,
       values = simulate(200, ar = 0.7, mean = 5, seed = 301)),
  list(name = "AUTO_RANDOM_WALK", doc = "A random walk with drift.", period = 1,
       values = cumsum(simulate(200, mean = 0.3, seed = 302))),
  list(name = "AUTO_I1_MA", doc = "An ARIMA(0, 1, 1).", period = 1,
       values = simulate(200, ma = -0.5, d = 1, seed = 303)),
  list(name = "AUTO_AIRLINE", doc = "The airline series above.", period = 12,
       values = arima_cases[[6]]$values),
  list(name = "AUTO_SEASONAL_AR", doc = "The seasonal AR series above.", period = 4,
       values = arima_cases[[7]]$values)
)
emit(
  "/// A series with R's differencing tests and `auto.arima` choice.",
  "pub struct AutoCase {",
  "    /// The series.",
  "    pub values: &'static [f64],",
  "    /// The season length; 1 for none.",
  "    pub period: usize,",
  "    /// `ndiffs(values)`: KPSS at the 5% level.",
  "    pub ndiffs: usize,",
  "    /// `nsdiffs(ts(values, frequency = period))`: seasonal strength; 0 without a season.",
  "    pub nsdiffs: usize,",
  "    /// `auto.arima(..., approximation = FALSE)`'s `(p, d, q, P, D, Q)`.",
  "    pub orders: [usize; 6],",
  "    /// Whether it kept a mean or drift.",
  "    pub constant: bool,",
  "}",
  ""
)
for (case in auto_cases) {
  x <- ts(case$values, frequency = case$period)
  nsd <- if (case$period > 1) nsdiffs(x) else 0
  fit <- auto.arima(x, approximation = FALSE, stepwise = TRUE)
  arma <- fit$arma  # p, q, P, Q, period, d, D
  constant <- any(c("intercept", "drift") %in% names(fit$coef))
  emit(
    sprintf("/// %s", case$doc),
    sprintf("pub const %s: AutoCase = AutoCase {", case$name),
    sprintf("    values: %s,", rust_array(case$values)),
    sprintf("    period: %d,", case$period),
    sprintf("    ndiffs: %d,", ndiffs(case$values)),
    sprintf("    nsdiffs: %d,", nsd),
    sprintf("    orders: [%s],", paste(arma[c(1, 6, 2, 3, 7, 4)], collapse = ", ")),
    sprintf("    constant: %s,", tolower(constant)),
    "};",
    ""
  )
}
emit(sprintf("/// All automatic-search reference cases.\npub const AUTO: &[&AutoCase] = &[%s];",
             paste0("&", vapply(auto_cases, function(c) c$name, ""), collapse = ", ")))


# R's ndiffs on the pmdarima series of `tests/it/auto_data.rs`, where R and pmdarima differ.
auto_text <- paste(readLines("tests/it/auto_data.rs"), collapse = "\n")
blocks <- regmatches(auto_text, gregexpr("pub const [A-Z0-9_]+: AutoCase = AutoCase \\{\\s*values: &\\[[^]]*\\]", auto_text))[[1]]
pmdarima_names <- sub("pub const ([A-Z0-9_]+):.*", "\\1", blocks)
pmdarima_ndiffs <- vapply(blocks, function(block) {
  body <- sub(".*values: &\\[", "", block)
  body <- sub("\\]$", "", body)
  ndiffs(as.numeric(strsplit(gsub("\\s", "", body), ",")[[1]]))
}, 0)
emit(
  "",
  "/// `ndiffs(values)` for each pmdarima series of `crate::auto_data` (in its order):",
  sprintf("/// %s.", paste(pmdarima_names, collapse = ", ")),
  sprintf("pub const PMDARIMA_SERIES_NDIFFS: &[usize] = %s;", rust_usize_array(pmdarima_ndiffs))
)

writeLines(lines, out)

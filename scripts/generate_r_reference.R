# ARIMA fits by exact maximum likelihood, and forecasts at the fitted coefficients.
emit(
  "/// A `stats::arima(values, order, seasonal, include.mean, method = \"ML\")` fit and its",
  "/// `predict(fit, n.ahead = 5)` forecasts.",
  "pub struct ArimaCase {",
  "    /// The series.",
  "    pub values: &'static [f64],",
  "    /// `(p, d, q)`.",
  "    pub order: [usize; 3],",
  "    /// `(P, D, Q)`.",
  "    pub seasonal: [usize; 3],",
  "    /// The season length; 0 without a seasonal part.",
  "    pub period: usize,",
  "    /// `include.mean`.",
  "    pub include_mean: bool,",
  "    /// The fitted AR coefficients.",
  "    pub ar: &'static [f64],",
  "    /// The fitted MA coefficients.",
  "    pub ma: &'static [f64],",
  "    /// The fitted seasonal AR coefficients.",
  "    pub seasonal_ar: &'static [f64],",
  "    /// The fitted seasonal MA coefficients.",
  "    pub seasonal_ma: &'static [f64],",
  "    /// The fitted mean (`intercept`); 0 without one.",
  "    pub mean: f64,",
  "    /// `fit$sigma2`.",
  "    pub sigma2: f64,",
  "    /// `fit$loglik`.",
  "    pub loglike: f64,",
  "    /// `predict(fit, 5)$pred`.",
  "    pub forecast_mean: &'static [f64],",
  "    /// `predict(fit, 5)$se`.",
  "    pub forecast_se: &'static [f64],",
  "}",
  ""
)

simulate <- function(n, ar = numeric(), ma = numeric(), d = 0, seasonal = NULL, mean = 0, seed) {
  set.seed(seed)
  model <- list(ar = ar, ma = ma)
  if (!is.null(seasonal)) {
    # Expand the seasonal polynomials into the non-seasonal ones.
    s <- seasonal$period
    sar <- c(1, rep(0, s * length(seasonal$ar)))
    for (i in seq_along(seasonal$ar)) sar[i * s + 1] <- -seasonal$ar[i]
    sma <- c(1, rep(0, s * length(seasonal$ma)))
    for (i in seq_along(seasonal$ma)) sma[i * s + 1] <- seasonal$ma[i]
    full_ar <- -convolve(c(1, -ar), rev(sar), type = "open")[-1]
    full_ma <- convolve(c(1, ma), rev(sma), type = "open")[-1]
    model <- list(ar = full_ar, ma = full_ma)
  }
  x <- as.numeric(arima.sim(model, n = n, n.start = 200)) + mean
  if (d > 0) for (i in seq_len(d)) x <- cumsum(c(10, x))[seq_len(n)]
  x
}

arima_cases <- list(
  list(name = "ARMA11", doc = "ARMA(1, 1) with a mean.", order = c(1, 0, 1), mean = TRUE,
       values = simulate(150, ar = 0.6, ma = 0.3, mean = 2, seed = 101)),
  list(name = "AR2", doc = "AR(2) with a mean.", order = c(2, 0, 0), mean = TRUE,
       values = simulate(200, ar = c(0.5, -0.3), mean = -1, seed = 102)),
  list(name = "MA2", doc = "MA(2) without a mean.", order = c(0, 0, 2), mean = FALSE,
       values = simulate(150, ma = c(0.4, -0.3), seed = 103)),
  list(name = "I1", doc = "ARIMA(1, 1, 1).", order = c(1, 1, 1), mean = FALSE,
       values = simulate(150, ar = 0.5, ma = -0.3, d = 1, seed = 104)),
  list(name = "I2", doc = "ARIMA(0, 2, 1).", order = c(0, 2, 1), mean = FALSE,
       values = simulate(150, ma = -0.5, d = 2, seed = 105)),
  list(name = "AIRLINE", doc = "The airline model ARIMA(0, 1, 1)(0, 1, 1, 12).",
       order = c(0, 1, 1), seasonal = c(0, 1, 1), period = 12, mean = FALSE,
       values = {
         w <- simulate(168, ma = -0.4, seasonal = list(ma = -0.6, period = 12), seed = 106)
         x <- w
         for (t in 13:length(x)) x[t] <- x[t - 12] + w[t]
         cumsum(x)
       }),
  list(name = "SAR4", doc = "ARIMA(1, 0, 0)(1, 0, 0, 4) with a mean.",
       order = c(1, 0, 0), seasonal = c(1, 0, 0), period = 4, mean = TRUE,
       values = simulate(160, ar = 0.4, seasonal = list(ar = 0.5, period = 4), mean = 3, seed = 107))
)

coef_part <- function(fit, prefix, count) {
  if (count == 0) return(numeric())
  as.numeric(fit$coef[paste0(prefix, seq_len(count))])
}

for (case in arima_cases) {
  seasonal <- if (is.null(case$seasonal)) c(0, 0, 0) else case$seasonal
  period <- if (is.null(case$period)) 0 else case$period
  fit <- arima(case$values, order = case$order,
               seasonal = list(order = seasonal, period = if (period > 0) period else NA),
               include.mean = case$mean, method = "ML",
               optim.control = list(maxit = 1000, reltol = 1e-12))
  pred <- predict(fit, n.ahead = 5)
  emit(
    sprintf("/// %s", case$doc),
    sprintf("pub const %s: ArimaCase = ArimaCase {", case$name),
    sprintf("    values: %s,", rust_array(case$values)),
    sprintf("    order: [%s],", paste(case$order, collapse = ", ")),
    sprintf("    seasonal: [%s],", paste(seasonal, collapse = ", ")),
    sprintf("    period: %d,", period),
    sprintf("    include_mean: %s,", tolower(case$mean)),
    sprintf("    ar: %s,", rust_array(coef_part(fit, "ar", case$order[1]))),
    sprintf("    ma: %s,", rust_array(coef_part(fit, "ma", case$order[3]))),
    sprintf("    seasonal_ar: %s,", rust_array(coef_part(fit, "sar", seasonal[1]))),
    sprintf("    seasonal_ma: %s,", rust_array(coef_part(fit, "sma", seasonal[3]))),
    sprintf("    mean: %s,", rust_float(if (case$mean) fit$coef[["intercept"]] else 0)),
    sprintf("    sigma2: %s,", rust_float(fit$sigma2)),
    sprintf("    loglike: %s,", rust_float(fit$loglik)),
    sprintf("    forecast_mean: %s,", rust_array(pred$pred)),
    sprintf("    forecast_se: %s,", rust_array(pred$se)),
    "};",
    ""
  )
}
emit(sprintf("/// All ARIMA reference cases.\npub const ARIMA: &[&ArimaCase] = &[%s];\n",
             paste0("&", vapply(arima_cases, function(c) c$name, ""), collapse = ", ")))


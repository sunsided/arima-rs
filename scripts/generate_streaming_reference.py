"""Generate statsmodels reference vectors for the streaming additions.

Writes `tests/it/steady_data.rs` and `tests/it/fourier_data.rs`. Run from the repository root:

    python3 -I scripts/generate_streaming_reference.py

Requires numpy and statsmodels (tested with statsmodels 0.14.0, numpy 1.24.3, scipy 1.11.1).
The vectors of `generate_reference.py` stay as they are; this script only adds new ones.
"""

import pathlib
import warnings

import numpy as np
import statsmodels
import pandas as pd
from statsmodels.tsa.deterministic import Fourier
from statsmodels.tsa.statespace.sarimax import SARIMAX

TESTS = pathlib.Path(__file__).resolve().parent.parent / "tests" / "it"
STEADY_OUTPUT = TESTS / "steady_data.rs"
FOURIER_OUTPUT = TESTS / "fourier_data.rs"
STEADY_HORIZON = 5


def rust_float(value):
    """Format a float as a Rust literal that round-trips exactly."""
    value = float(value)
    return "f64::NAN" if np.isnan(value) else repr(value)


def rust_array(values):
    """Format floats as a Rust array literal that round-trips exactly."""
    if len(values) == 0:
        return "&[]"
    body = ",\n".join(f"        {rust_float(v)}" for v in values)
    return f"&[\n{body},\n    ]"


def seasonal_arma(ar, ma, sar, sma, period, sigma2, n, seed):
    """Simulate `n` values of a seasonal ARMA after a burn-in."""
    rng = np.random.default_rng(seed)
    burn = 300
    e = rng.standard_normal(n + burn) * np.sqrt(sigma2)
    seasonal_ar = np.zeros(len(sar) * period + 1)
    seasonal_ar[0] = 1
    for i, c in enumerate(sar):
        seasonal_ar[(i + 1) * period] = -c
    seasonal_ma = np.zeros(len(sma) * period + 1)
    seasonal_ma[0] = 1
    for i, c in enumerate(sma):
        seasonal_ma[(i + 1) * period] = c
    ar_poly = np.convolve(np.r_[1, -np.array(ar, float)], seasonal_ar)
    ma_poly = np.convolve(np.r_[1, np.array(ma, float)], seasonal_ma)
    y = np.zeros_like(e)
    for t in range(len(y)):
        value = sum(ma_poly[j] * e[t - j] for j in range(len(ma_poly)) if t - j >= 0)
        value -= sum(ar_poly[j] * y[t - j] for j in range(1, len(ar_poly)) if t - j >= 0)
        y[t] = value
    return y[burn:]


# (name, doc, ar, d, ma, seasonal (ar, ma, period), mean, sigma2, length, missing index, seed)
STEADY_CASES = [
    ("ARMA11", "ARMA(1, 1), 120 values.", [0.5], 0, [0.3], ([], [], 0), 0.0, 1.3, 120, None, 1),
    ("ARMA21", "ARMA(2, 1) with mean 2, 120 values.", [0.5, -0.2], 0, [0.4], ([], [], 0), 2.0, 0.8, 120, None, 2),
    ("SMA4", "ARIMA(0, 0, 1)(0, 0, 1, 4), 160 values: it converges late.", [], 0, [0.3], ([], [0.6], 4), 0.0, 1.0, 160, None, 3),
    ("MISSING", "ARMA(1, 2) with values 50 and 90 missing, both after convergence.", [0.7], 0, [0.6, 0.3], ([], [], 0), 0.0, 1.0, 140, (50, 90), 4),
    ("DRIFT", "ARIMA(1, 1, 1) with drift 0.3, 121 values: the filter differences the raw values.", [0.4], 1, [0.5], ([], [], 0), 0.3, 1.0, 121, None, 5),
]


def steady_case(name, doc, ar, d, ma, seasonal, mean, sigma2, length, missing, seed):
    """Render one `SteadyCase` from statsmodels' filter with its default tolerance."""
    sar, sma, period = seasonal
    w = seasonal_arma(ar, ma, sar, sma, period, sigma2, length - d, seed) + mean
    y = w
    for _ in range(d):
        y = np.concatenate([[10.0], 10.0 + np.cumsum(y)])
    if missing is not None:
        y = y.copy()
        y[list(missing)] = np.nan
    w = np.diff(y, n=d) - mean
    model = SARIMAX(w, order=(len(ar), 0, len(ma)), seasonal_order=(len(sar), 0, len(sma), period), trend="n")
    assert model.ssm.tolerance == 1e-19
    results = model.filter([*ar, *ma, *sar, *sma, sigma2])
    if d == 0:
        forecast = results.get_forecast(STEADY_HORIZON)
        forecast_mean, forecast_variance = forecast.predicted_mean + mean, forecast.var_pred_mean
    else:
        forecast_mean, forecast_variance = [], []
    lines = [f"/// {doc}", f"pub const {name}: SteadyCase = SteadyCase {{"]
    arrays = {
        "ar": ar,
        "ma": ma,
        "seasonal_ma": sma,
        "values": y,
        "innovation_values": results.filter_results.forecasts_error[0],
        "innovation_variances": results.filter_results.forecasts_error_cov[0, 0],
        "forecast_mean": forecast_mean,
        "forecast_variance": forecast_variance,
    }
    lines += [f"    {field}: {rust_array(values)}," for field, values in arrays.items()]
    lines += [
        f"    d: {d},",
        f"    period: {period},",
        f"    mean: {rust_float(mean)},",
        f"    sigma2: {rust_float(sigma2)},",
        f"    period_converged: {results.filter_results.period_converged},",
        "};",
    ]
    return "\n".join(lines)


def write_steady():
    """Write the steady-state reference module."""
    header = f'''//! statsmodels reference vectors for the filter's steady-state mode.
//!
//! Generated by `scripts/generate_streaming_reference.py` with statsmodels {statsmodels.__version__}.
//! Do not edit by hand; rerun the script instead.

/// A series filtered by statsmodels with its default `ssm.tolerance = 1e-19`.
///
/// Innovations come from `SARIMAX(diff(values, d) - mean, order=(p, 0, q),
/// seasonal_order=(0, 0, Q, s)).filter(params)`.
pub struct SteadyCase {{
    /// The AR coefficients.
    pub ar: &'static [f64],
    /// The MA coefficients.
    pub ma: &'static [f64],
    /// The seasonal MA coefficients.
    pub seasonal_ma: &'static [f64],
    /// The raw series. `NaN` marks a missing value.
    pub values: &'static [f64],
    /// `filter_results.forecasts_error[0]`, one per differenced value.
    pub innovation_values: &'static [f64],
    /// `filter_results.forecasts_error_cov[0, 0]`, one per differenced value.
    pub innovation_variances: &'static [f64],
    /// `get_forecast({STEADY_HORIZON}).predicted_mean + mean` after the series; empty for `d > 0`.
    pub forecast_mean: &'static [f64],
    /// `get_forecast({STEADY_HORIZON}).var_pred_mean`; empty for `d > 0`.
    pub forecast_variance: &'static [f64],
    /// The differencing order.
    pub d: usize,
    /// The season length; 0 for non-seasonal cases.
    pub period: usize,
    /// The mean of the differenced series.
    pub mean: f64,
    /// The innovation variance.
    pub sigma2: f64,
    /// `filter_results.period_converged`: the step at which statsmodels froze the covariance.
    pub period_converged: usize,
}}

/// All steady-state reference cases.
pub const ALL: &[&SteadyCase] = &[{", ".join(f"&{case[0]}" for case in STEADY_CASES)}];
'''
    body = "\n\n".join(steady_case(*case) for case in STEADY_CASES)
    STEADY_OUTPUT.write_text(header + "\n" + body + "\n")



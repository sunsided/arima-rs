FOURIER_CASES = [
    ("WEEKLY", "Period 7, K = 3, from t = 0.", 7.0, 3, 0, 30),
    ("MONTHLY", "Period 12, K = 6: statsmodels keeps the Nyquist sine, the crate drops it.", 12.0, 6, 0, 30),
    ("YEARLY", "Period 365.25, K = 4, from t = 1000.", 365.25, 4, 1000, 40),
    ("HOURLY_YEAR", "Period 8766, K = 2, from t = 123456.", 8766.0, 2, 123456, 20),
]


def fourier_case(name, doc, period, k, t0, rows):
    """Render one `FourierCase` from statsmodels' `deterministic.Fourier`."""
    generator = Fourier(period, k)
    if t0 == 0:
        terms = generator.in_sample(pd.RangeIndex(rows)).to_numpy()
    else:
        terms = generator.out_of_sample(rows, pd.RangeIndex(t0)).to_numpy()
    if 2 * k == period:
        terms = np.delete(terms, 2 * k - 2, axis=1)
    lines = [f"/// {doc}", f"pub const {name}: FourierCase = FourierCase {{"]
    lines += [
        f"    period: {rust_float(period)},",
        f"    k: {k},",
        f"    t0: {t0},",
        f"    columns: {terms.shape[1]},",
        f"    values: {rust_array(terms.ravel())},",
        "};",
    ]
    return "\n".join(lines)


def write_fourier():
    """Write the Fourier reference module."""
    header = f'''//! statsmodels `deterministic.Fourier` reference regressors.
//!
//! Generated by `scripts/generate_streaming_reference.py` with statsmodels {statsmodels.__version__}.
//! Do not edit by hand; rerun the script instead.

/// Fourier regressors from statsmodels for rows `t0, t0 + 1, ...`, row-major, with the
/// Nyquist sine removed where `2K = period`.
pub struct FourierCase {{
    /// The seasonal period.
    pub period: f64,
    /// The number of harmonics.
    pub k: usize,
    /// The time index of the first row.
    pub t0: u64,
    /// The number of columns per row.
    pub columns: usize,
    /// The regressors, row-major.
    pub values: &'static [f64],
}}

/// All Fourier reference cases.
pub const ALL: &[&FourierCase] = &[{", ".join(f"&{case[0]}" for case in FOURIER_CASES)}];
'''
    body = "\n\n".join(fourier_case(*case) for case in FOURIER_CASES)
    FOURIER_OUTPUT.write_text(header + "\n" + body + "\n")


if __name__ == "__main__":
    warnings.simplefilter("ignore")
    write_steady()
    write_fourier()
